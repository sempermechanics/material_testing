package com.sempermechanics.semper.ui.examples

import android.app.Application
import android.widget.TextView
import androidx.recyclerview.widget.RecyclerView
import androidx.test.core.app.ApplicationProvider
import com.sempermechanics.semper.R
import com.sempermechanics.semper.fixtures.idleUntil
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.Robolectric
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/** Credits & licences (ADR-031, TD-349): every credit, every library, and the licence texts and notices in full. */
@RunWith(RobolectricTestRunner::class)
@Config(application = Application::class)
class LicencesActivityTest {

    private val app = ApplicationProvider.getApplicationContext<Application>()
    private val blocks by lazy { LicencePage.build(app, app.assets) }
    private val page by lazy { blocks.joinToString("\n") { it.text } }

    private val libraries by lazy {
        val raw = app.resources.openRawResource(R.raw.aboutlibraries).use { it.readBytes().decodeToString() }
        LicencePage.parseLibraries(raw)
    }

    @Test
    fun `the page opens on the example credits`() {
        Robolectric.buildActivity(LicencesActivity::class.java).setup().use { controller ->
            val list = controller.get().findViewById<RecyclerView>(R.id.rvLicences)
            idleUntil("the page is built") { (list.adapter?.itemCount ?: 0) > 0 }
            list.measure(0, 0)
            list.layout(0, 0, 1080, 2400)
            assertEquals("Example data", (list.getChildAt(0) as TextView).text.toString())
        }
    }

    @Test
    fun `every credit and every licence text is on the page`() {
        listOf(
            "Sanjeev Koirala",
            "doi:10.5281/zenodo.1172068",
            "doi:10.17632/z3yc9z84tk.3",
            "National Technology & Engineering Solutions of Sandia",
            // The BSD-3 clause DICe's binary redistribution asks to be reproduced.
            "Redistributions in binary form must reproduce the above copyright",
            "Apache License",
            "Mozilla Public License Version 2.0",
            // The codecs OpenCV links into libsemper.
            "Jean-loup Gailly and Mark Adler",
            "PNG Reference Library License version 2",
            "Independent JPEG Group",
            "Sam Leffler",
            "Copyright (c) 2010, Google Inc.",
            "NVIDIA Corporation",
            // The MIT and BSD libraries whose notice travels with them.
            "Checker Framework qualifiers",
            "Code generated by the Protocol Buffer compiler",
        ).forEach { assertTrue(it, it in page) }
        val dice = blocks.dropWhile { it.text != "DICe-BSD-3-Clause" }.drop(1).takeWhile { !it.heading }
        assertTrue(dice.toString(), dice.isNotEmpty() && dice.none { "//" in it.text })
    }

    @Test
    fun `every library in the APK is listed with its licence`() {
        val (libs, _) = libraries
        assertTrue(libs.size.toString(), libs.size > 50)
        listOf("androidx.activity:activity", "com.squareup.okhttp3:okhttp", "com.google.firebase:firebase-auth")
            .forEach { id -> assertTrue(id, libs.any { it.id == id } && "($id)" in page) }
        libs.forEach { assertTrue(it.id, it.licences.isNotEmpty()) }
    }

    @Test
    fun `a library under a licence the page has no text for fails here`() {
        // Apache-2.0's text is on the page; the Google terms are links. A new licence, or a new
        // MIT / BSD library, needs its notice in assets/licences before this passes.
        val (libs, licences) = libraries
        val linkOnly = setOf(
            "Android Software Development Kit License",
            "Play Core Software Development Kit Terms of Service",
            "Play Integrity API Terms of Service",
        )
        val withText = mapOf(
            "org.checkerframework:checker-qual" to "checker-qual-MIT.txt",
            "androidx.datastore:datastore-preferences-external-protobuf" to "protobuf-BSD-3-Clause.txt",
        )
        val texts = app.assets.list(LicencePage.LICENCES_DIR).orEmpty().toSet()
        libs.forEach { lib ->
            lib.licences.forEach { id ->
                val name = licences[id]?.name ?: id
                when {
                    id == "Apache-2.0" || name in linkOnly -> Unit
                    else -> assertTrue("${lib.id} is under $name", withText[lib.id] in texts)
                }
            }
        }
    }

    @Test
    fun `the notices bundled in Play services are on the page`() {
        val headings = blocks.filter { it.heading }.map { it.text }
        assertTrue(headings.toString(), "Notices in Google Play services and Firebase" in headings)
        assertTrue(headings.toString(), headings.any { "Guava" in it })
        assertFalse("no notice heading is left raw", "### " in page)
    }

    @Test
    fun `a licence's paragraphs reflow to the screen and keep their words`() {
        val licence = """
            // ****************************
            //
            // Redistribution and use in source and binary forms, with or without
            // modification, are permitted.
            //
            // 1. Redistributions of source code must retain the above copyright
            // notice.
            // ****************************
        """.trimIndent()
        assertEquals(
            "Redistribution and use in source and binary forms, with or without modification, are permitted." +
                "\n\n1. Redistributions of source code must retain the above copyright notice.",
            LicencePage.reflow(licence),
        )
    }

    @Test
    fun `a licence that is not a comment keeps its slashes and drops its rules`() {
        val licence = "Mozilla Public License Version 2.0\n==================================\n\n" +
            "1.1. \"Contributor\"\n    means each individual // or entity\n    that contributes."
        assertEquals(
            "Mozilla Public License Version 2.0\n\n" +
                "1.1. \"Contributor\" means each individual // or entity that contributes.",
            LicencePage.reflow(licence),
        )
    }
}
